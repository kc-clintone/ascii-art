package main

import "testing"

func TestRenderAsciiArt(t *testing.T) {
	letterMap := map[rune][]string{
		' ': {
			"      ",
			"      ",
			"      ",
			"      ",
			"      ",
			"      ",
			"      ",
			"      ",
		},
		'H': {
			" _    _  ",
			"| |  | | ",
			"| |__| | ",
			"|  __  | ",
			"| |  | | ",
			"|_|  |_| ",
			"         ",
			"         ",
		},
		'e': {
			"       ",
			"       ",
			"  ___  ",
			` / _ \ `,
			`|  __/ `,
			` \___| `,
			"       ",
			"       ",
		},
		'l': {
			" _  ",
			"| | ",
			"| | ",
			"| | ",
			"| | ",
			"|_| ",
			"    ",
			"    ",
		},
		'o': {
			`        `,
			`        `,
			`  ___   `,
			` / _ \  `,
			`| (_) | `,
			` \___/  `,
			`        `,
			`        `,
		},
		'T': {
			" _______  ",
			"|__   __| ",
			"   | |    ",
			"   | |    ",
			"   | |    ",
			"   |_|    ",
			"          ",
			"          ",
		},
		'r': {
			"       ",
			"       ",
			" _ __  ",
			"| '__| ",
			"| |    ",
			"|_|    ",
			"       ",
			"       ",
		},
		'@': {
			`          `,
			`   ____   `,
			`  / __ \  `,
			" / / _` | ",
			`| | (_| | `,
			` \ \__,_| `,
			`  \____/  `,
			`          `,
		},
		'_': {
			"         ",
			"         ",
			"         ",
			"         ",
			"         ",
			"         ",
			" ______  ",
			"|______| ",
		},
		'0': {
			`        `,
			`  ___   `,
			` / _ \  `,
			`| | | | `,
			`| |_| | `,
			` \___/  `,
			`        `,
			`        `,
		},
	}

	t.Run("empty input", func(t *testing.T) {
		input := ""
		expected := ""

		output := AsciiArt(input, letterMap)

		if output != expected {
			t.Error("Expected empty input to produce nothing")
		}
	})
}
